import com.google.zxing.*;
import com.google.zxing.common.BitMatrix;
import com.google.zxing.common.HybridBinarizer;
import com.google.zxing.qrcode.QRCodeWriter;
import com.google.zxing.qrcode.QRCodeReader;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.Map;

public final class QrCodeService {
    private static final String PREFIX = "QRATTENDANCE:3:";
    private static volatile MobileAttendanceServer mobileServer;
    static void setMobileServer(MobileAttendanceServer server) { mobileServer = server; }
    private QrCodeService() { }

    public static BufferedImage generate(String roll) throws WriterException {
        return generate(roll, 360);
    }

    public static BufferedImage generate(String roll, int size) throws WriterException {
        return generate(roll, size, System.currentTimeMillis());
    }

    static BufferedImage generate(String roll, int size, long now) throws WriterException {
        String payload = PREFIX + "0:" + Base64.getUrlEncoder().withoutPadding()
                .encodeToString(roll.getBytes(StandardCharsets.UTF_8));
        MobileAttendanceServer mobile = mobileServer;
        if (mobile != null) payload = mobile.urlFor(roll, now);
        return generatePayload(payload, size);
    }

    static BufferedImage generatePayload(String payload, int size) throws WriterException {
        BitMatrix bits = new QRCodeWriter().encode(payload, BarcodeFormat.QR_CODE, size, size,
                Map.of(EncodeHintType.CHARACTER_SET, "UTF-8", EncodeHintType.MARGIN, 4));
        BufferedImage image = new BufferedImage(bits.getWidth(), bits.getHeight(), BufferedImage.TYPE_INT_RGB);
        for (int y = 0; y < bits.getHeight(); y++) for (int x = 0; x < bits.getWidth(); x++)
            image.setRGB(x, y, bits.get(x, y) ? 0x000000 : 0xFFFFFF);
        return image;
    }

    public static String decode(BufferedImage image) throws ReaderException, IOException {
        return decode(image, System.currentTimeMillis());
    }

    static String decode(BufferedImage image, long now) throws ReaderException, IOException {
        if (image == null) throw new IOException("Choose a supported PNG, JPEG or BMP image.");
        int width = image.getWidth(), height = image.getHeight();
        int[] pixels = image.getRGB(0, 0, width, height, null, 0, width);
        BinaryBitmap bitmap = new BinaryBitmap(new HybridBinarizer(new RGBLuminanceSource(width, height, pixels)));
        String payload = new QRCodeReader().decode(bitmap, Map.of(DecodeHintType.TRY_HARDER, true)).getText();
        if ((payload.startsWith("http://") || payload.startsWith("https://")) && mobileServer != null) return mobileServer.decodeUrl(payload, now);
        if (payload.startsWith("QRATTENDANCE:1:") || payload.startsWith("QRATTENDANCE:2:"))
            throw new IOException("This QR code is outdated. Open the student's current QR code and scan again.");
        if (!payload.startsWith(PREFIX)) throw new IOException("This is not a student QR code generated by this application.");
        try {
            String[] parts = payload.substring(PREFIX.length()).split(":", -1);
            if (parts.length != 2) throw new IllegalArgumentException();
            if (!parts[0].equals("0")) throw new IllegalArgumentException();
            String roll = new String(Base64.getUrlDecoder().decode(parts[1]), StandardCharsets.UTF_8);
            if (roll.isBlank() || roll.length() > 30 || roll.chars().anyMatch(Character::isISOControl))
                throw new IllegalArgumentException();
            return roll;
        } catch (IllegalArgumentException exception) {
            throw new IOException("The student QR code is invalid.");
        }
    }
}
